#!/usr/bin/env python3
"""
Builds server/src/xbrl/ci2016.generated.ts from MCA's C&I taxonomy 2016 (the package the MCA XBRL validator uses,
Taxonomy-2016-03-31.zip, unzipped). Dev-time only: the app ships the generated facts, not the taxonomy.

  python3 -I server/scripts/xbrl-taxonomy.py <taxonomy dir containing in-ci-ent-2016-03-31.xsd> server/src/xbrl/ci2016.generated.ts

What it extracts:
  CONCEPTS  name -> "prefix|type|periodType|balance|flags|typedDomain"  (flags: a = abstract, d = dimension, h = hypercube)
  TYPES     in-ca-types / in-gaap-types restrictions -> { base, enum?, pattern? }
  AXIS_DEFAULTS  axis -> default member (never written in a context)
  CALC      calculation linkbase arcs per role: [parent, child, weight]
"""
import json, os, re, sys
import xml.etree.ElementTree as ET

src, out = sys.argv[1], sys.argv[2]
XS = '{http://www.w3.org/2001/XMLSchema}'
XBRLI = '{http://www.xbrl.org/2003/instance}'
XBRLDT = '{http://xbrl.org/2005/xbrldt}'
XL = '{http://www.w3.org/1999/xlink}'
LB = '{http://www.xbrl.org/2003/linkbase}'

SHORT = {
    'xbrli:monetaryItemType': 'monetary', 'xbrli:stringItemType': 'string', 'nonnum:domainItemType': 'member',
    'nonnum:textBlockItemType': 'text', 'num:percentItemType': 'percent', 'xbrli:sharesItemType': 'shares',
    'xbrli:decimalItemType': 'decimal', 'xbrli:dateItemType': 'date', 'xbrli:booleanItemType': 'boolean',
    'num:perShareItemType': 'perShare', 'xbrli:pureItemType': 'pure', 'xbrli:integerItemType': 'integer',
    'xbrli:nonNegativeIntegerItemType': 'integer',
}

concepts = {}
for prefix, path in (('in-gaap', 'IN-GAAP/in-gaap-2016-03-31.xsd'), ('in-ca', 'IN-CA/in-ca-2016-03-31.xsd')):
    root = ET.parse(os.path.join(src, path)).getroot()
    for el in root.findall(XS + 'element'):
        name = el.get('name')
        t = el.get('type', '')
        t = SHORT.get(t, t)
        sg = el.get('substitutionGroup', '')
        flags = ('a' if el.get('abstract') == 'true' else '') + ('d' if sg == 'xbrldt:dimensionItem' else '') + ('h' if sg == 'xbrldt:hypercubeItem' else '')
        td = (el.get(XBRLDT + 'typedDomainRef') or '').split('#')[-1].replace(prefix + '_', '')
        concepts[name] = '|'.join([prefix, t, (el.get(XBRLI + 'periodType') or '')[:1], (el.get(XBRLI + 'balance') or '')[:1], flags, td])

types = {}
for prefix, path in (('in-ca-types', 'IN-CA/in-ca-types-2016-03-31.xsd'),):
    root = ET.parse(os.path.join(src, path)).getroot()
    for ct in root.iter(XS + 'complexType'):
        r = ct.find('.//' + XS + 'restriction')
        if r is None:
            continue
        d = {'base': r.get('base')}
        en = [e.get('value') for e in r.findall(XS + 'enumeration')]
        pa = [p.get('value') for p in r.findall(XS + 'pattern')]
        if en: d['enum'] = en
        if pa: d['pattern'] = pa
        types[prefix + ':' + ct.get('name')] = d

calc = {}
for folder in ('IN-GAAP/CAL', 'IN-CA/CAL'):
    for fn in sorted(os.listdir(os.path.join(src, folder))):
        root = ET.parse(os.path.join(src, folder, fn)).getroot()
        for cl in root.iter(LB + 'calculationLink'):
            role = cl.get(XL + 'role').split('/')[-1]
            loc = {l.get(XL + 'label'): l.get(XL + 'href').split('#')[1].split('_', 1)[1] for l in cl.findall(LB + 'loc')}
            arcs = [[loc[a.get(XL + 'from')], loc[a.get(XL + 'to')], float(a.get('weight'))] for a in cl.findall(LB + 'calculationArc')]
            if arcs:
                calc.setdefault(role, []).extend(arcs)

# Axis defaults (dimension-default arcs): a fact for the default member carries no dimension in its context.
defaults = {}
for folder in ('IN-GAAP/DEF', 'IN-CA/DEF'):
    for fn in sorted(os.listdir(os.path.join(src, folder))):
        root = ET.parse(os.path.join(src, folder, fn)).getroot()
        for dl in root.iter(LB + 'definitionLink'):
            loc = {l.get(XL + 'label'): l.get(XL + 'href').split('#')[1].split('_', 1)[1] for l in dl.findall(LB + 'loc')}
            for a in dl.findall(LB + 'definitionArc'):
                if a.get(XL + 'arcrole', '').endswith('/dimension-default'):
                    defaults[loc[a.get(XL + 'from')]] = loc[a.get(XL + 'to')]

with open(out, 'w') as f:
    f.write('/* Generated by server/scripts/xbrl-taxonomy.py from MCA\'s C&I taxonomy 2016 (Taxonomy-2016-03-31). Do not edit. */\n')
    f.write('/* eslint-disable */\n')
    f.write('export const CONCEPTS: Record<string, string> = ' + json.dumps(concepts, separators=(',', ':')) + ';\n')
    f.write('export const TYPES: Record<string, { base: string; enum?: string[]; pattern?: string[] }> = ' + json.dumps(types, separators=(',', ':')) + ';\n')
    f.write('export const AXIS_DEFAULTS: Record<string, string> = ' + json.dumps(defaults, separators=(',', ':')) + ';\n')
    f.write('export const CALC: Record<string, [string, string, number][]> = ' + json.dumps(calc, separators=(',', ':')) + ';\n')
print(len(concepts), 'concepts,', len(types), 'types,', sum(len(v) for v in calc.values()), 'calc arcs in', len(calc), 'roles')
